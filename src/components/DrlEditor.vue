                  <el-select
                    v-model="config.package"
                    filterable
                    allow-create
                    default-first-option
                    placeholder="选择或输入包名"
                    class="w-full"
                    size="large"
                  >
                    <el-option
                      v-for="item in packageOptions"
                      :key="item.value"
                      :label="item.label"
                      :value="item.value"
                    />
                  </el-select>
                </el-form-item>
                <el-form-item>
                  <template #label>
