<script setup lang="ts">
import { ref, onMounted, computed, watch } from 'vue'
import { ElMessage, ElMessageBox } from 'element-plus'
import {
  Trash2, HelpCircle, Lightbulb, Plus,
  Code2, Settings, ClipboardList, FileText, AlertTriangle,
  Package, FileInput, Globe, FileText as FileDescription, Tag, Target, Search, Zap,
  CheckCircle, XCircle, Wand2, Eye, Terminal, X, Upload, GripVertical
} from 'lucide-vue-next'
import HelpDialog from './HelpDialog.vue'
import PreviewDialog from './PreviewDialog.vue'
import CodeStatistics from './CodeStatistics.vue'
import RuleConditionBuilder from './RuleConditionBuilder.vue'
import RuleActionBuilder from './RuleActionBuilder.vue'
import { generateDrlCode, formatTimestamp } from '@/utils/drl'
import { packageOptions, importOptions, globalOptions } from '@/constants/drlOptions'
import { sampleConfig, sampleRules } from '@/constants/sampleData'
import { extractClassNamesFromRules, getMissingImports, extractPackagePrefix } from '@/utils/importDetector'
import { parseDrlFile, validateDrlFile } from '@/utils/drlParser'
import { v4 as uuidv4 } from 'uuid'
import { VueDraggable } from 'vue-draggable-plus'

// 数据定义
const config = ref<Config>({
  package: '',
  imports: [],
  globals: [],
  description: ''
})

const rules = ref<Rule[]>([])
const activeRules = ref<number | string>(0)

// 控制折叠面板显示
const activeConfig = ref<string>('config') // 全局配置折叠状态
const activeRuleList = ref<string>('ruleList') // 规则列表折叠状态

// 控制帮助弹窗显示
const showHelpDialog = ref(false)

// 控制代码预览弹窗显示
const showPreviewDialog = ref(false)

// 自动导入模式（默认开启）
const autoImportMode = ref(true)

// 高级模式状态
const advancedMode = ref(false)
const manualDrlCode = ref('')

// 固定的文件ID和时间戳（在整个会话中保持不变）
const fixedDrlId = ref(uuidv4())
const fixedTimestamp = ref(formatTimestamp())

// 缓存自动生成的代码（使用固定的UUID，避免重复生成）
const autoGeneratedCode = computed(() => {
  return generateDrlCode(
    config.value.package,
    config.value.imports,
    config.value.globals,
    rules.value,
    config.value.description,
    fixedDrlId.value,
    fixedTimestamp.value
  )
})

// 检测缺失的导入
const missingImports = computed(() => {
  const classNames = extractClassNamesFromRules(rules.value)
  const packagePrefix = extractPackagePrefix(config.value.imports)
  return getMissingImports(config.value.imports, classNames, packagePrefix)
})

// 是否有缺失的导入
const hasMissingImports = computed(() => missingImports.value.length > 0)

/**
 * 自动添加缺失的导入
 */
const autoAddImports = () => {
  if (missingImports.value.length > 0) {
    config.value.imports = [...config.value.imports, ...missingImports.value]
    ElMessage.success(`已自动添加 ${missingImports.value.length} 个导入`)
  } else {
    ElMessage.info('没有需要添加的导入')
  }
}

// 监听规则变化，自动导入模式下自动添加缺失的导入
watch(
  () => [rules.value, autoImportMode.value],
  () => {
    if (autoImportMode.value && hasMissingImports.value && !advancedMode.value) {
      // 延迟执行，避免频繁触发
      setTimeout(() => {
        if (missingImports.value.length > 0) {
          config.value.imports = [...config.value.imports, ...missingImports.value]
        }
      }, 500)
    }
  },
  { deep: true }
)

/**
 * 添加新规则
 */
const addRule = () => {
  rules.value.push({
    name: 'rule_' + Date.now(),
    enabled: true,
    salience: 10,
    noLoop: false,
    lockOnActive: false,
    when: '',
    then: '',
    visualMode: true  // 默认开启可视化模式
  })
  // 自动展开新添加的规则
  activeRules.value = rules.value.length - 1
}

/**
 * 确认删除规则
 */
const confirmRemoveRule = (index: number) => {
  // @ts-ignore
  const ruleName = rules.value[index].name || `规则 ${index + 1}`
  ElMessageBox.confirm(
    `确定要删除规则"${ruleName}"吗？此操作不可恢复。`,
    '删除确认',
    {
      confirmButtonText: '确定删除',
      cancelButtonText: '取消',
      type: 'warning',
    }
  ).then(() => {
    removeRule(index)
    ElMessage({
      type: 'success',
      message: '规则已删除'
    })
  }).catch(() => {
    // 用户取消删除
  })
}

/**
 * 删除规则
 */
const removeRule = (index: number) => {
  rules.value.splice(index, 1)
  // 删除规则后调整 activeRules
  if (typeof activeRules.value === 'number' && activeRules.value >= rules.value.length && rules.value.length > 0) {
    activeRules.value = rules.value.length - 1
  } else if (rules.value.length === 0) {
    activeRules.value = -1
  }
}

/**
 * 加载示例规则
 */
const loadSample = () => {
  // 设置全局配置
  config.value = { ...sampleConfig }

  // 设置规则示例
  rules.value = [...sampleRules]

  // 展开第一个规则
  activeRules.value = 0
}

/**
 * 导入 DRL 文件
 */
const importDrlFile = (file: File) => {
  const reader = new FileReader()

  reader.onload = (e) => {
    try {
      const content = e.target?.result as string

      // 验证文件格式
      const validation = validateDrlFile(content)
      if (!validation.valid) {
        ElMessage.error(validation.error || '文件格式不正确')
        return
      }

      // 解析文件
      const parsed = parseDrlFile(content)

      // 填充配置
      config.value = {
        package: parsed.package,
        imports: parsed.imports,
        globals: parsed.globals,
        description: parsed.description
      }

      // 填充规则
      rules.value = parsed.rules

      // 展开第一个规则
      if (rules.value.length > 0) {
        activeRules.value = 0
      }

      ElMessage.success(`成功导入 ${parsed.rules.length} 个规则`)
    } catch (error) {
      console.error('解析 DRL 文件失败:', error)
      ElMessage.error('解析文件失败，请检查文件格式')
    }
  }

  reader.onerror = () => {
    ElMessage.error('读取文件失败')
  }

  reader.readAsText(file)
}

/**
 * 处理文件上传
 */
const handleFileUpload = (file: File) => {
  // 检查文件类型
  if (!file.name.endsWith('.drl')) {
    ElMessage.warning('请上传 .drl 格式的文件')
    return false
  }

  // 确认导入
  ElMessageBox.confirm(
    '导入文件将覆盖当前所有配置和规则，是否继续？',
    '确认导入',
    {
      confirmButtonText: '确定导入',
      cancelButtonText: '取消',
      type: 'warning',
    }
  ).then(() => {
    importDrlFile(file)
  }).catch(() => {
    // 用户取消
  })

  return false // 阻止默认上传行为
}

/**
 * 生成 DRL 代码
 */
const generateDRL = (): string => {
  if (advancedMode.value) {
    return manualDrlCode.value
  }
  return autoGeneratedCode.value
}

/**
 * 处理高级模式切换
 */
const handleAdvancedModeToggle = () => {
  if (!advancedMode.value) {
    // 开启高级模式
    ElMessageBox.confirm(
      '开启高级模式后，您可以直接编辑 DRL 代码。手动修改的内容将覆盖表单生成的代码，并影响下载和复制的结果。',
      '开启高级模式',
      {
        confirmButtonText: '确定开启',
        cancelButtonText: '取消',
        type: 'warning',
        distinguishCancelAndClose: true
      }
    ).then(() => {
      // 用户确认，同步当前表单数据到高级模式
      // 每次打开高级模式时都更新代码，确保表单数据同步
      manualDrlCode.value = autoGeneratedCode.value
      // 然后开启高级模式
      advancedMode.value = true
      ElMessage({
        type: 'success',
        message: '已开启高级模式，可以手动编辑代码'
      })
    }).catch(() => {
      // 用户取消
    })
  } else {
    // 关闭高级模式
    // 检查代码是否有修改（比较去除空格后的内容）
    const currentCode = manualDrlCode.value.trim()
    const generatedCode = autoGeneratedCode.value.trim()
    const hasModification = currentCode !== generatedCode

    if (!hasModification) {
      // 没有修改，直接退出
      advancedMode.value = false
      ElMessage.info('已退出高级模式')
      return
    }

    // 有修改，询问是否同步代码到表单
    ElMessageBox.confirm(
      '检测到您在高级模式中修改了代码，是否要将修改同步到表单？',
      '退出高级模式',
      {
        confirmButtonText: '同步到表单',
        cancelButtonText: '放弃修改',
        type: 'warning',
        distinguishCancelAndClose: true
      }
    ).then(() => {
      // 用户选择同步，解析代码到表单
      try {
        const validation = validateDrlFile(manualDrlCode.value)
        if (!validation.valid) {
          ElMessage.error(validation.error || '代码格式不正确，无法同步到表单')
          return
        }

        const parsed = parseDrlFile(manualDrlCode.value)

        // 同步配置
        config.value = {
          package: parsed.package,
          imports: parsed.imports,
          globals: parsed.globals,
          description: parsed.description
        }

        // 同步规则
        rules.value = parsed.rules

        // 关闭高级模式
        advancedMode.value = false

        ElMessage.success('已同步代码到表单')
      } catch (error) {
        console.error('解析代码失败:', error)
        ElMessage.error('解析代码失败，请检查代码格式')
      }
    }).catch((action) => {
      // 用户选择放弃修改或关闭对话框
      if (action === 'cancel') {
        // 放弃修改，直接关闭高级模式
        advancedMode.value = false
        ElMessage.info('已放弃高级模式中的修改')
      }
      // 如果是 close，不做任何操作，保持在高级模式
    })
  }
}

// 组件挂载时初始化
onMounted(() => {
  // loadSample()
  addRule()
})
</script>

