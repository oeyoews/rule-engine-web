                  <el-select
                    v-model="config.globals"
                    multiple
                    placeholder="选择全局变量"
                    class="w-full"
                    collapse-tags
                    collapse-tags-tooltip
                    :max-collapse-tags="4"
                    size="large"
                  >
                    <el-option
                      v-for="item in globalOptions"
                      :key="item.value"
                      :label="item.label"
                      :value="item.value"
                    />
                  </el-select>
                </el-form-item>
                <el-form-item>
                  <template #label>
                    <div class="flex items-center gap-2 ml-1">
                      <FileDescription :size="16" class="text-green-600" />
                      <span>描述</span>
                    </div>
